// Records the Java 8 line metrics (ascent, descent, leading) that UYAP Editör uses
// to place text vertically. Writes src/udf/java-metrics.js.
// Horizontal advances need no table: UYAP measures them unhinted, which equals the
// advance widths of the metric-compatible Liberation fonts.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { buildDir, compile, runJava8, toolDir } from "./java.mjs";

const root = join(toolDir, "..", "..");
const faces = ["regular", "bold", "italic", "boldItalic"];
const pointsFile = join(buildDir, "code-points.txt");
const rawFile = join(buildDir, "java-metrics.txt");
compile("JavaMetrics.java");
writeFileSync(pointsFile, "32");
runJava8("JavaMetrics", [pointsFile, rawFile]);

const [version, ...lines] = readFileSync(rawFile, "utf8").trim().split(/\r?\n/);
const table = { java: version, fonts: {} };
for (const line of lines) {
  const [family, style, size, ascent, descent, leading] = line.split("|");
  const sizes = ((table.fonts[family.toLowerCase()] ??= {})[faces[Number(style)]] ??= []);
  sizes[Number(size) - 1] = [Number(ascent), Number(descent), Number(leading)];
}
const output = join(root, "src", "udf", "java-metrics.js");
writeFileSync(output, `// Generated by tools/udf/metrics.mjs from the Java ${version} runtime. Do not edit.
// [ascent, descent, leading] for sizes 1–96 of each family and face.
export default ${JSON.stringify(table)};
`);
console.log(`Java ${version} → ${output} (${(readFileSync(output).length / 1024).toFixed(1)} KiB)`);
